  function schedule(source, apply, forced) {
    const known = forced || lookupKnown(source);
    if (known) {
      apply(known);
      return;
    }
    if (DICTIONARY_ONLY_APPS.has(appKey)) return;
    pending += 1;
    updateBadge();
    requestTranslation(source)
      .then((translated) => {
        if (translated) apply(translated);
      })
      .finally(() => {
        pending -= 1;
        updateBadge();
      });
  }

  function translateTextNode(node) {
    if (!node.isConnected) return;
    const raw = node.nodeValue || '';
    const source = raw.trim();
    if (!shouldTranslate(source)) return;
    const parent = node.parentElement;
    if (!parent) return;
    const dictionaryOnly = DICTIONARY_ONLY_APPS.has(appKey);
    const inTree = dictionaryOnly && !!parent.closest('[role="tree"]');
    const inPalette = dictionaryOnly && !!parent.closest('.palette-dlg');
    if (parent.closest(excludeSelector) && !inTree && !inPalette) return;
    if (!dictionaryOnly && !parent.closest(uiSelector)) return;
    if (!isVisible(parent) && !(parent instanceof HTMLOptionElement) && !(dictionaryOnly && lookupKnown(source))) return;
    schedule(source, (translated) => {
      if (node.isConnected && node.nodeValue === raw) {
        const lead = raw.match(/^\s*/)[0];
        const trail = raw.match(/\s*$/)[0];
        node.nodeValue = lead + translated + trail;
      }
    }, contextualTranslation(source, parent));
  }

  function translateAttributes(element) {
    if (!(element instanceof Element)) return;
    if (appKey !== 'building-design' && !isVisible(element)) return;
    const attributes = ['title', 'aria-label', 'placeholder'];
    if (appKey === 'building-design') attributes.push('data-tip', 'data-tip-desc');
    if (element instanceof HTMLInputElement && /^(?:button|submit|reset)$/i.test(element.type)) {
      attributes.push('value');
    }
    for (const name of attributes) {
      const raw = element.getAttribute(name);
      const source = raw && raw.trim();
      if (!shouldTranslate(source)) continue;
      schedule(source, (translated) => {
        if (element.getAttribute(name) === raw) element.setAttribute(name, translated);
      }, contextualTranslation(source, element));
    }
  }

  function scan(root) {
    if (!root) return;
    if (root.nodeType === Node.TEXT_NODE) {
      translateTextNode(root);
      return;
    }
    if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_NODE) return;
    if (root.nodeType === Node.ELEMENT_NODE) translateAttributes(root);
    const tipSelector = appKey === 'building-design' ? '[data-tip],[data-tip-desc],' : '';
    const elements = root.querySelectorAll(`${tipSelector}[title],[aria-label],[placeholder],input[type="button"],input[type="submit"],input[type="reset"]`);
    for (const element of elements) translateAttributes(element);
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) translateTextNode(node);
  }

