  function shouldTranslate(text) {
    if (!text || text.length > 320 || !/[A-Za-z]/.test(text)) return false;
    if (CJK.test(text) && appKey !== 'building-design') return false;
    if (SKIP_EXACT.has(text)) return false;
    if (appKey === 'building-design' && text === '<None>') return true;
    if (appKey === 'building-design' && text === '<Last viewed>') return true;
    if (appKey === 'building-design' && text === 'OK') return true;
    if (appKey === 'building-design' && /^(?:TOP|BOTTOM|NORTH|SOUTH|EAST|WEST)$/.test(text)) return true;
    if (/^[A-Z0-9+#.-]{1,3}$/.test(text)) return false;
    if (/^(?:https?:\/\/|mailto:|www\.)/i.test(text)) return false;
    if (/^[\d\s.,:;+\-–—/()%#]+$/.test(text)) return false;
    if (/[{}<>]|=>|::|\\|\$\{/.test(text)) return false;
    if (/^(?:Sheet|Slide|Page)\s*\d+$/i.test(text)) return false;
    if (/^[-+]?[\w.-]+\.(?:js|ts|css|html|json|png|jpe?g|gif|svg|pdf|docx?|xlsx?|pptx?|zip|txt)$/i.test(text)) return false;
    return true;
  }

  function isVisible(element) {
    if (!(element instanceof Element) || !element.isConnected) return false;
    if (element.closest('[hidden],[aria-hidden="true"]')) return false;
    const style = getComputedStyle(element);
    if (style.display === 'none' || style.visibility === 'hidden' || style.visibility === 'collapse') return false;
    if (Number.parseFloat(style.opacity) === 0) return false;
    return element.getClientRects().length > 0;
  }

